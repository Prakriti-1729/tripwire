"""Write the results tables + numeric RQ answers into README.md between RESULTS markers.
Every number comes from results/<slug>/*.json."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tripwire.common import DEFAULT_MODEL, RESULTS, ROOT, read_json, slug  # noqa: E402
from tripwire.templates import FAMILIES, group_of  # noqa: E402

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
NAMES = {"tripwire": "**Tripwire** (probe, plain-trained)", "tripwire_aug": "Tripwire + B-aug (plain + group-B templates)",
         "diff_of_means": "Diff-of-means direction (no training)", "tfidf": "TF-IDF + LR on prompt text",
         "guard": "Granite Guardian 3.2 3B-A800M (guard model)"}


def f2(x):
    return "–" if x is None else f"{x:.2f}"


def f3(x):
    return "–" if x is None else f"{x:.3f}"


def pct(x, d=1):
    return "–" if x is None else f"{100 * x:.{d}f}%"


def load(model):
    rd = RESULTS / slug(model)
    out = {k: read_json(rd / f"{k}.json") for k in ("metrics", "selection", "layer_sweep")}
    out["latency"] = read_json(rd / "latency.json") if (rd / "latency.json").exists() else None
    return out


def aug_sentence(t, g):
    """Data-driven description of what group-B augmentation does to unseen group A and seen group B."""
    dA = g["group_A"]["auroc"] - t["group_A"]["auroc"]
    dB = g["group_B"]["auroc"] - t["group_B"]["auroc"]
    word = lambda d: "raises" if d > 0.01 else ("lowers" if d < -0.01 else "barely changes")  # noqa: E731
    return (f"Adding group-B templates to training {word(dB)} group-B AUROC ({f3(t['group_B']['auroc'])} → "
            f"{f3(g['group_B']['auroc'])}; TPR {f2(t['group_B']['tpr'])} → {f2(g['group_B']['tpr'])}: templates seen in "
            f"training, on unseen behaviors) but {'also raises' if dA > 0.01 else 'does not help'} the still-unseen group A ({f3(t['group_A']['auroc'])} → "
            f"{f3(g['group_A']['auroc'])}; TPR {f2(t['group_A']['tpr'])} → {f2(g['group_A']['tpr'])}; translation TPR "
            f"{f2(t['per_family']['translation']['tpr'])} → {f2(g['per_family']['translation']['tpr'])}): template "
            f"robustness learned this way is template-specific.")


def build(model, small=None):
    R = load(model)
    M, S, SW, L = R["metrics"], R["selection"], R["layer_sweep"], R["latency"]
    mt = M["methods"]
    lines = []
    A = lines.append
    A(f"_Generated by `scripts/make_report.py` from `results/{slug(model)}/`. Model: `{model}`._\n")
    A(f"**Chosen probe** (selected on plain-prompt validation AUROC only): layer **{S['layer']}** of {S['n_layers']}, "
      f"`{S['pooling']}`-token pooling, `{S['method']}` (C={S['C']}); threshold set at 1% FPR on plain validation "
      f"benign prompts.\n")

    # ---- headline
    A("### Headline results (test split)\n")
    A("| Detector | Plain AUROC | Plain TPR / FPR | Wrapped AUROC | Wrapped TPR / FPR | XSTest-safe FPR | "
      "Catch rate on complied jailbreaks (keyword / judge) |")
    A("|---|---|---|---|---|---|---|")
    rq3, rq3j = M.get("rq3", {}), M.get("rq3_judge", {})
    for m in ("tripwire", "tripwire_aug", "diff_of_means", "tfidf", "guard"):
        if m not in mt:
            continue
        d = mt[m]
        c1 = rq3.get("ALL", {}).get("catch", {}).get(m, {}).get("rate")
        c2 = rq3j.get("ALL", {}).get("catch", {}).get(m, {}).get("rate")
        A(f"| {NAMES[m]} | {f3(d['plain_test']['auroc'])} | {f2(d['plain_test']['tpr'])} / {f2(d['plain_test']['fpr'])} | "
          f"{f3(d['wrapped_test']['auroc'])} | {f2(d['wrapped_test']['tpr'])} / {f2(d['wrapped_test']['fpr'])} | "
          f"{f2(d['xstest_safe']['fpr'])} | {f2(c1)} / {f2(c2)} |")
    n = mt["tripwire"]
    A(f"\nPlain test: {n['plain_test']['n_pos']} harmful / {n['plain_test']['n_neg']} benign. Wrapped test: "
      f"{n['wrapped_test']['n_pos']} harmful / {n['wrapped_test']['n_neg']} benign (10 template families). "
      f"XSTest: {n['xstest_safe']['n_neg']} safe prompts. "
      f"Complied jailbreaks: keyword n={rq3.get('ALL', {}).get('n_complied')}, judge n={rq3j.get('ALL', {}).get('n_complied')} "
      f"(of {rq3.get('ALL', {}).get('n')} harmful test prompts, plain + wrapped). "
      f"Tripwire/TF-IDF thresholds: 1% FPR on plain val; guard: its own Yes/No decision.\n")

    # ---- RQ answers in numbers
    t = mt["tripwire"]
    A("### The research questions, in numbers\n")
    # RQ1
    def best(pl, key, method="lr", min_layer=1):
        items = [(v[method][key], int(k.split("/")[1])) for k, v in SW.items() if k.startswith(pl + "/")
                 and int(k.split("/")[1]) >= min_layer]
        return max(items)

    def first_reach(pl, key, thr, method="lr"):
        ls = sorted(int(k.split("/")[1]) for k in SW if k.startswith(pl + "/"))
        for l in ls:
            if SW[f"{pl}/{l}"][method][key] >= thr:
                return l
        return None
    nl = S["n_layers"]
    A(f"- **RQ1 (where?)** On plain prompts harmfulness is linearly decodable almost everywhere: LR on last-token "
      f"activations reaches plain-test AUROC ≥ 0.99 from layer {first_reach('last', 'test_auroc', 0.99)} of {nl}. "
      f"The harder topic-matched JailbreakBench subset (harmful vs benign on the *same* topics) peaks at AUROC "
      f"{f3(best('last', 'test_auroc_jbb_matched')[0])} at layer {best('last', 'test_auroc_jbb_matched')[1]} (last-token) / "
      f"{f3(best('mean', 'test_auroc_jbb_matched')[0])} at layer {best('mean', 'test_auroc_jbb_matched')[1]} (mean-pooled): "
      f"the concept sharpens in the middle-to-late layers. Selection on plain validation data picked layer {S['layer']} "
      f"({S['pooling']}).")
    bw = best("mean", "wrapped_test_auroc")
    bwl = best("last", "wrapped_test_auroc")
    A(f"- **RQ2 (does it generalize to unseen jailbreak templates?)** Partly. The plain-trained probe drops from "
      f"AUROC {f3(t['plain_test']['auroc'])} (plain) to {f3(t['wrapped_test']['auroc'])} (harmful-wrapped vs "
      f"benign-wrapped), with TPR {f2(t['wrapped_test']['tpr'])} at FPR {f2(t['wrapped_test']['fpr'])} on the benign-wrapped "
      f"control. Inside most families the ranking is still near-perfect (per-family AUROC ≥ 0.96 for "
      f"{sum(t['per_family'][f]['auroc'] >= 0.96 for f in FAMILIES)}/10 families) but the template shifts scores, so a "
      f"threshold calibrated on plain prompts misses many (e.g. fiction TPR {f2(t['per_family']['fiction']['tpr'])}, "
      f"prefix-injection {f2(t['per_family']['prefix_injection']['tpr'])}, translation {f2(t['per_family']['translation']['tpr'])}). "
      f"It fails outright on base64 (AUROC {f3(t['per_family']['base64']['auroc'])}) and payload splitting "
      f"(AUROC {f3(t['per_family']['payload_split']['auroc'])}). The benign-wrapped control FPR stays ≤ "
      f"{f2(max(t['per_family'][f]['fpr'] for f in FAMILIES))} in every family, so the probe is *not* just detecting "
      f"template text. "
      + aug_sentence(t, mt["tripwire_aug"]) + " "
      f"Post-hoc (not used for selection), the most robust readout in the "
      f"sweep is mean-pooled layer {bw[1]} (wrapped AUROC {f3(bw[0])}) vs best last-token layer {bwl[1]} ({f3(bwl[0])}).")
    if rq3:
        a, j = rq3["ALL"], rq3j.get("ALL")
        from tripwire.templates import GROUP_B
        src = rq3j if j else rq3
        shareB = sum(src[f]["n_complied"] for f in GROUP_B) / max(1, src["ALL"]["n_complied"])
        A(f"- **RQ3 (does it catch what the model misses?)** Qwen went along with {a['n_complied']} of {a['n']} harmful test "
          f"prompts by the keyword definition (no refusal phrase), but the keyword count is inflated by garbled base64 decodes "
          f"and payload-split answers that never get to the request; by the stricter judge definition (Granite Guardian "
          f"rates the response harmful) it complied with {j['n_complied'] if j else '–'}. Tripwire flags "
          f"**{pct(a['catch']['tripwire']['rate'], 0)}** (keyword) / **{pct(j['catch']['tripwire']['rate'], 0) if j else '–'}** "
          f"(judge) of those; the B-augmented probe flags {pct(a['catch']['tripwire_aug']['rate'], 0)} / "
          f"{pct(j['catch']['tripwire_aug']['rate'], 0) if j else '–'}, but {pct(shareB, 0)} of the judged-harmful completions "
          f"come from group-B families whose templates it was trained on, so that number is optimistic for novel attacks. The misses concentrate in prefix injection "
          f"({rq3j['prefix_injection']['n_complied'] if j else '–'} judged-harmful completions, Tripwire catches "
          f"{pct(rq3j['prefix_injection']['catch']['tripwire']['rate'], 0) if j else '–'}), fiction, translation and payload "
          f"splitting. (The guard's judge-definition catch rate is not independent: the judge is the same model family.)")
    x = t["xstest_safe"]
    A(f"- **RQ4 (over-refusal?)** On the {x['n_neg']} XSTest safe-but-scary prompts Tripwire flags "
      f"**{pct(x['fpr'])}** (95% CI {pct(x['fpr_ci95'][0])}–{pct(x['fpr_ci95'][1])}), vs {pct(mt['guard']['xstest_safe']['fpr'])} "
      f"for the guard model, {pct(mt['tripwire_aug']['xstest_safe']['fpr'])} for the B-augmented probe and "
      f"{pct(mt['tfidf']['xstest_safe']['fpr'])} for TF-IDF. On XSTest's unsafe contrast prompts Tripwire's TPR is "
      f"{f2(t['xstest_unsafe']['tpr'])} (AUROC safe-vs-unsafe {f3(t['xstest_all']['auroc'])}).")
    if L:
        l256 = L["lengths"].get("256") or list(L["lengths"].values())[0]
        g2 = f", dense `{L['guard2'].split('/')[-1]}` +{l256['guard2_added_ms']:.1f} ms" if L.get("guard2") else ""
        po = L.get("probe_op_only")
        dl = [v["probe_added_ms"] for v in L["lengths"].values()]
        deltas = ", ".join(f"{d:+.1f}" for d in dl)
        const = max(dl) - min(dl) < 1.0 and min(dl) > 0
        A(f"- **RQ5 (cost?)** At ~256 prompt tokens, batch size 1: prefill {l256['a_prefill']['median_ms']:.1f} ms; prefill + "
          f"Tripwire {l256['b_prefill_plus_probe']['median_ms']:.1f} ms (difference {l256['probe_added_ms']:+.1f} ms, "
          f"{l256['probe_overhead_pct']:+.1f}%; "
          f"{deltas} ms at the three lengths"
          + (", i.e. roughly constant: one extra host sync to read the score on this time-shared GPU)" if const else
             "; noisy on this shared GPU)")
          + (f"; the probe op itself costs {L['probe_op_amortized']['median_ms'] * 1000:.0f} µs of GPU time (amortized), "
             f"{po['median_ms']:.1f} ms if measured with its own host sync on this time-shared GPU"
             if po and L.get("probe_op_amortized") else "")
          + f". A separate guard pass adds +{l256['guard_added_ms']:.1f} ms (MoE `{L['guard'].split('/')[-1]}`){g2}. "
          f"Early abort (stop after layer {L['layer']} when the probe fires) saves {l256['early_abort_saving_pct']:.0f}% "
          f"of prefill time on flagged prompts.\n")

    # ---- per family
    A("### Per template family (wrapped test; harmful TPR / benign-wrapped FPR, AUROC)\n")
    A("| Family | Group | Tripwire TPR / FPR | Tripwire AUROC | +B-aug TPR / FPR | TF-IDF TPR / FPR | Guard TPR / FPR | "
      "Model complied (keyword / judge) | Tripwire catch on complied (keyword / judge) |")
    A("|---|---|---|---|---|---|---|---|---|")
    for f in ["none"] + FAMILIES:
        g = "–" if f == "none" else group_of(f)
        get = (lambda m: mt[m]["plain_test"]) if f == "none" else (lambda m: mt[m]["per_family"][f])
        r, rj = rq3.get(f, {}), rq3j.get(f, {})
        A(f"| {'plain (no template)' if f == 'none' else f} | {g} | {f2(get('tripwire')['tpr'])} / {f2(get('tripwire')['fpr'])} | "
          f"{f3(get('tripwire')['auroc'])} | {f2(get('tripwire_aug')['tpr'])} / {f2(get('tripwire_aug')['fpr'])} | "
          f"{f2(get('tfidf')['tpr'])} / {f2(get('tfidf')['fpr'])} | {f2(get('guard')['tpr'])} / {f2(get('guard')['fpr'])} | "
          f"{f2(r.get('model_compliance_rate'))} / {f2(rj.get('model_compliance_rate'))} | "
          f"{f2(r.get('catch', {}).get('tripwire', {}).get('rate'))} (n={r.get('n_complied')}) / "
          f"{f2(rj.get('catch', {}).get('tripwire', {}).get('rate'))} (n={rj.get('n_complied')}) |")
    A("")

    # ---- XSTest
    A("### Over-refusal (XSTest)\n")
    A("| Detector | Safe prompts flagged (FPR) | 95% CI | Unsafe contrast prompts flagged (TPR) | AUROC |")
    A("|---|---|---|---|---|")
    for m in ("tripwire", "tripwire_aug", "diff_of_means", "tfidf", "guard"):
        if m in mt:
            d = mt[m]
            A(f"| {NAMES[m]} | {f3(d['xstest_safe']['fpr'])} | {f3(d['xstest_safe']['fpr_ci95'][0])}–"
              f"{f3(d['xstest_safe']['fpr_ci95'][1])} | {f3(d['xstest_unsafe']['tpr'])} | {f3(d['xstest_all']['auroc'])} |")
    A("")

    # ---- latency
    if L:
        A(f"### Latency (batch 1, median / p90 ms over {L['runs']} interleaved runs after {L['warmup']} warmups, {L['gpu']})\n")
        cols = [("a_prefill", "Prefill"), ("b_prefill_plus_probe", "Prefill + Tripwire"),
                ("d_early_abort_at_L", f"Early abort at L{L['layer']}"),
                ("c_guard_forward", "Guard (MoE 3B-A800M)"), ("c2_guard2_forward", "Guard (dense 2B)")]
        cols = [c for c in cols if c[0] in list(L["lengths"].values())[0]]
        A("| Prompt tokens | " + " | ".join(c[1] for c in cols) + " | Tripwire Δ | Guard Δ (MoE / dense) |")
        A("|---|" + "---|" * (len(cols) + 2))
        for k, r in L["lengths"].items():
            A(f"| {r['prompt_tokens']} | " + " | ".join(f"{r[c]['median_ms']:.1f} / {r[c]['p90_ms']:.1f}" for c, _ in cols)
              + f" | {r['probe_added_ms']:+.1f} ms ({r['probe_overhead_pct']:+.1f}%) | "
              f"+{r.get('guard_overhead_pct', 0):.0f}% / +{r.get('guard2_overhead_pct', 0):.0f}% |")
        gb, ga = L.get("gpu_status_before", {}), L.get("gpu_status_after", {})
        A(f"\nShared GPU: utilization from all processes {gb.get('util_pct')}% before / {ga.get('util_pct')}% after the "
          f"benchmark, {gb.get('n_compute_procs_incl_ours')}–{ga.get('n_compute_procs_incl_ours')} compute processes on the "
          f"device (incl. ours). Absolute times are inflated by contention; treat differences of a few ms as noise.")
        if L.get("probe_op_only"):
            po = L["probe_op_only"]
            A(f"Isolated probe op (pooling + {po.get('dim')}-dim dot product + host copy, 256-token hidden state): "
              f"median {po['median_ms']:.3f} ms, p90 {po['p90_ms']:.3f} ms over {po['n']} runs; this is dominated by "
              f"waiting for the GPU's time slice at the host sync"
              + (f". Amortized GPU time per probe op (1000 ops per sync): {L['probe_op_amortized']['median_ms'] * 1000:.1f} µs."
                 if L.get("probe_op_amortized") else "."))
        A("")

    # ---- details: data, probe selection, layer sweep
    man_path = ROOT / "data" / "manifest.json"
    if man_path.exists():
        man = read_json(man_path)
        p, src = man["plain"], man["plain_by_source"]
        A("### Dataset (from `data/manifest.json`)\n")
        A("| Split | Harmful | Benign | Total |")
        A("|---|---|---|---|")
        for s in ("train", "val", "test"):
            h, b = p[f"{s}_harmful"], p[f"{s}_benign"]
            A(f"| {s} | {h} | {b} | {h + b} |")
        th, tb = sum(p[f"{s}_harmful"] for s in ("train", "val", "test")), sum(p[f"{s}_benign"] for s in ("train", "val", "test"))
        A(f"| **all plain** | {th} | {tb} | {th + tb} |")
        A("\nSources after deduplication: " + ", ".join(f"{k} {v}" for k, v in src.items())
          + f". Wrapped test set: {man['wrapped_test']} prompts; group-B augmentation set (train/val behaviors only): "
          f"{man['wrapped_aug']}; XSTest: {man['xstest']['safe']} safe + {man['xstest']['unsafe']} unsafe."
          + (" Build log: " + "; ".join(man.get("log", [])) + "." if man.get("log") else "") + "\n")

    A(f"### Probe selection (top 5 of every layer × pooling × method by plain-val AUROC; {S['n_train']} train / "
      f"{S['n_val']} val prompts)\n")
    A("| Rank | Layer | Pooling | Method | Val AUROC (4 dp) | Val TPR @ 1% FPR |")
    A("|---|---|---|---|---|---|")
    for i, c in enumerate(S["top5"], 1):
        A(f"| {i} | {c['layer']} | {c['pooling']} | {c['method']} | {c['val_auroc']:.4f} | {c['val_tpr_at_1fpr']:.3f} |")
    A(f"\nRule: {S['rule']}. Chosen probe threshold (raw logit score): {S['threshold']:.3f}. "
      f"TF-IDF baseline: C={S['tfidf']['C']}, val AUROC {S['tfidf']['val_auroc']:.3f}. "
      f"B-aug probe: C={S['aug']['C']}.\n")

    nl = S["n_layers"]
    show = sorted({1, 2, 4, 6, 8, 10, 12, 13, 14, 16, 18, 20, 22, 24, 26, nl} & set(range(1, nl + 1)))
    A("### Layer sweep (test AUROC per layer; LR = logistic regression, DoM = difference of means)\n")
    A("| Layer | Pooling | LR plain | DoM plain | LR wrapped | DoM wrapped | LR topic-matched JBB | LR XSTest safe-vs-unsafe |")
    A("|---|---|---|---|---|---|---|---|")
    for pl in ("last", "mean"):
        for l in show:
            r = SW.get(f"{pl}/{l}")
            if not r:
                continue
            mark = " ◀ chosen" if (l == S["layer"] and pl == S["pooling"]) else ""
            A(f"| {l}{mark} | {pl} | {f3(r['lr']['test_auroc'])} | {f3(r['dom']['test_auroc'])} | "
              f"{f3(r['lr']['wrapped_test_auroc'])} | {f3(r['dom']['wrapped_test_auroc'])} | "
              f"{f3(r['lr']['test_auroc_jbb_matched'])} | {f3(r['lr']['xstest_auroc'])} |")
    A(f"\nFull per-layer numbers (all {nl + 1} hidden states, both poolings, both methods, val and test) are in "
      f"`results/{slug(model)}/layer_sweep.json`. Layer 0 (embeddings) is excluded from selection: with last-token "
      f"pooling it is the same chat-template token for every prompt (AUROC "
      f"{f3(SW['last/0']['lr']['test_auroc'])}).\n")

    # ---- scale comparison
    if small:
        Rs = load(small)
        ms, ss = Rs["metrics"]["methods"], Rs["selection"]
        A(f"### Scale comparison: `{small}` vs `{model}`\n")
        A("| Model | Chosen layer / pooling | Plain AUROC | Wrapped AUROC | Wrapped TPR / FPR | XSTest-safe FPR | "
          "Catch on complied (keyword / judge) | Model compliance (keyword / judge) |")
        A("|---|---|---|---|---|---|---|---|")
        for name, MM, SS in ((small, Rs["metrics"], ss), (model, M, S)):
            d = MM["methods"]["tripwire"]
            r1, r2 = MM.get("rq3", {}).get("ALL", {}), MM.get("rq3_judge", {}).get("ALL", {})
            A(f"| `{name.split('/')[-1]}` | {SS['layer']}/{SS['n_layers']} {SS['pooling']} | {f3(d['plain_test']['auroc'])} | "
              f"{f3(d['wrapped_test']['auroc'])} | {f2(d['wrapped_test']['tpr'])} / {f2(d['wrapped_test']['fpr'])} | "
              f"{f2(d['xstest_safe']['fpr'])} | {f2(r1.get('catch', {}).get('tripwire', {}).get('rate'))} / "
              f"{f2(r2.get('catch', {}).get('tripwire', {}).get('rate'))} | {f2(r1.get('model_compliance_rate'))} / "
              f"{f2(r2.get('model_compliance_rate'))} |")
        A("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--small", default="Qwen/Qwen2.5-1.5B-Instruct")
    a = ap.parse_args()
    small = a.small if (RESULTS / slug(a.small) / "metrics.json").exists() else None
    block = build(a.model, small)
    readme = ROOT / "README.md"
    text = readme.read_text() if readme.exists() else f"# Tripwire\n\n{START}\n{END}\n"
    if START not in text:
        text += f"\n{START}\n{END}\n"
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: f"{START}\n{block}\n{END}", text, flags=re.S)
    readme.write_text(text)
    (RESULTS / "report.md").write_text(block + "\n")
    print(block)


if __name__ == "__main__":
    main()
